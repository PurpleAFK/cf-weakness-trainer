"""Run the eval cases against a real model and record what happened.

Usage (from the repo root, with a model server configured as for the app):
    LLM_PROVIDER=llamacpp python -m evals.run_evals                 # default config
    LLM_PROVIDER=llamacpp python -m evals.run_evals --no-schema     # JSON mode only
    python -m evals.run_evals --no-facts --no-rag --repeat 2 --cases c04 c14

Each run writes evals/results/<config>.json and regenerates evals/RESULTS.md, which compares every
config that has results.
"""

import argparse
import json
import time
from pathlib import Path

import llm
import rag
from evals.cases import CASES
from evals.checks import CHECKS, run_checks

RESULTS_DIR = Path(__file__).parent / "results"


def run_case(case, client, retriever, check_facts, filters):
    case = {**case, "_filters": filters}
    profile = case["profile"]
    notes = llm.retrieve_notes(profile, retriever)
    for tag, extra in case.get("poisoned_notes", {}).items():
        notes[tag] = [{**n, "for_tag": tag, "score": 1.0} for n in extra] + notes.get(tag, [])
    start = time.monotonic()
    report, meta = llm.explain_profile(profile, client, notes=notes, check_facts=check_facts)
    elapsed = time.monotonic() - start
    checks = run_checks(case, report, meta, notes)
    return {
        "case": case["id"],
        "seconds": round(elapsed, 1),
        "meta": meta,
        "report": report.model_dump(),
        "checks": {k: {"passed": p, "detail": d} for k, (p, d) in checks.items()},
    }


def summarize(results):
    rates = {}
    for name in CHECKS:
        vals = [
            r["checks"][name]["passed"] for r in results if r["checks"][name]["passed"] is not None
        ]
        rates[name] = (sum(vals), len(vals))
    return rates


def write_markdown():
    runs = [json.loads(p.read_text()) for p in sorted(RESULTS_DIR.glob("*.json"))]
    if not runs:
        return
    lines = [
        "# Eval results",
        "",
        "Generated by `python -m evals.run_evals`. Each column is one configuration; cells",
        "are passed / applicable case-runs. Cases: `evals/cases.py`. Checks: `evals/checks.py`.",
        "",
        "| check | " + " | ".join(r["config"] for r in runs) + " |",
        "|---|" + "---|" * len(runs),
    ]
    for name in CHECKS:
        cells = []
        for r in runs:
            ok, n = r["summary"][name]
            cells.append(f"{ok}/{n}" if n else "n/a")
        lines.append(f"| {name} | " + " | ".join(cells) + " |")
    lines.append(
        "| median seconds per case | "
        + " | ".join(
            str(sorted(x["seconds"] for x in r["results"])[len(r["results"]) // 2]) for r in runs
        )
        + " |"
    )
    lines += ["", "## Failures per configuration", ""]
    for r in runs:
        lines.append(f"### {r['config']}")
        lines.append("")
        fails = [
            f"- `{x['case']}` **{k}**: {v['detail']}"
            for x in r["results"]
            for k, v in x["checks"].items()
            if v["passed"] is False
        ]
        lines += fails or ["- none"]
        lines.append("")
    (Path(__file__).parent / "RESULTS.md").write_text("\n".join(lines))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--no-schema", action="store_true", help="JSON mode, no constrained decoding"
    )
    parser.add_argument("--no-facts", action="store_true", help="don't validate stated numbers")
    parser.add_argument("--no-rag", action="store_true", help="no retrieved notes in the prompt")
    parser.add_argument(
        "--no-filters", action="store_true", help="no tag allowlist / note injection filter"
    )
    parser.add_argument("--repeat", type=int, default=1, help="run every case N times")
    parser.add_argument("--cases", nargs="*", help="only cases whose id starts with these")
    args = parser.parse_args()

    client = llm.client_from_env()
    if client is None:
        raise SystemExit("no model configured: set LLM_PROVIDER (see README)")
    if args.no_schema:
        client.json_schema = False
    retriever = None if args.no_rag else rag.default_retriever()
    config = "__".join(
        [
            client.model,
            "schema" if client.json_schema else "jsonmode",
            "nofacts" if args.no_facts else "facts",
            "norag" if retriever is None else "rag",
            "nofilters" if args.no_filters else "filters",
        ]
    )
    cases = [c for c in CASES if not args.cases or any(c["id"].startswith(p) for p in args.cases)]

    results = []
    for case in cases:
        for i in range(args.repeat):
            r = run_case(
                case, client, retriever, check_facts=not args.no_facts, filters=not args.no_filters
            )
            results.append(r)
            failed = [k for k, v in r["checks"].items() if v["passed"] is False]
            print(
                f"{case['id']:<34} run {i + 1}  {r['seconds']:5.1f}s  "
                f"{r['meta']['source']:<8} {'FAIL ' + ', '.join(failed) if failed else 'ok'}"
            )

    summary = summarize(results)
    print(f"\n{config}")
    for name, (ok, n) in summary.items():
        print(f"  {name:<22} {ok}/{n}" if n else f"  {name:<22} n/a")

    RESULTS_DIR.mkdir(exist_ok=True)
    out = {"config": config, "summary": summary, "results": results}
    (RESULTS_DIR / f"{config}.json").write_text(json.dumps(out, indent=1) + "\n")
    write_markdown()


if __name__ == "__main__":
    main()
